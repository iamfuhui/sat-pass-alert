function detectInitialLang() {
  try {
    const s = localStorage.getItem('spa_lang')
    if (s && ['zh-CN', 'en', 'ja'].includes(s)) return s
  } catch {}
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'zh-CN') || 'zh-CN'
  if (nav.toLowerCase().startsWith('ja')) return 'ja'
  if (nav.toLowerCase().startsWith('en')) return 'en'
  return 'zh-CN'
}
export const currentLang = ref(detectInitialLang())
export function setCurrentLang(lang) {
  if (!['zh-CN', 'en', 'ja'].includes(lang)) return
  currentLang.value = lang
  try { localStorage.setItem('spa_lang', lang) } catch {}
  if (typeof document !== 'undefined') document.documentElement.lang = lang
}
